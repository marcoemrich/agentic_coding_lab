import { describe, it } from 'vitest';
import { verify } from './examples.js';

describe('MHPCO claim office CLI', () => {
  it('empty quote costs only the 5 G fee', () => verify(1));
  it('plain sword has 100 G base plus 10 G first assessment plus 5 G fee = 115 G', () => verify(2));
  it('plain amulet has 60 G base plus 6 G assessment plus 5 G fee = 71 G', () => verify(3));
  it('plain staff has 80 G base plus 8 G assessment plus 5 G fee = 93 G', () => verify(4));
  it('plain potion has 40 G base plus 4 G assessment plus 5 G fee = 49 G', () => verify(5));
  it('one rune has 25 G base plus assessment and fee = 33 G after rounding up', () => verify(6));
  it('one moonstone has 25 G base plus assessment and fee = 33 G after rounding up', () => verify(7));
  it('2 runes have 50 G base and cost 60 G with assessment and fee', () => verify(8));
  it('3 runes form a 60 G block and cost 71 G', () => verify(9));
  it('4 runes have 100 G base with no block and cost 115 G', () => verify(10));
  it('7 runes have 175 G base with no block and cost 198 G after rounding', () => verify(11));
  it('2 runes and 1 moonstone have 75 G base, no mixed-type block, and cost 88 G', () => verify(12));
  it('3 runes and 3 moonstones form separate 60 G blocks and cost 137 G', () => verify(13));
  it('cursed sword for newcomer costs 165 G including 50 G curse and 10 G assessment', () => verify(14));
  it('enchantment 5 sword adds 30 G while enchantment 4 sword does not', () => verify(15));
  it('cursed enchantment 5 sword adds both 50 G and 30 G surcharges', () => verify(16));
  it('cursed enchantment 4 sword adds only 50 G curse surcharge', () => verify(17));
  it('exactly 2 years earns 20 G loyalty discount on a sword', () => verify(18));
  it('cursed sword and plain amulet: 160 G policy base, 50 G item curse, 16 G assessment, 5 G fee = 231 G', () => verify(19));
  it('long-standing second quote of new cursed enchantment 7 sword costs 160 G with loyalty, assessment and follow-up', () => verify(20));
  it('premium fractional 197.5 G is rounded up only at end to 198 G', () => verify(21));
  it('quote unknown broomstick exits non-zero with stderr and no results on stdout', () => verify(22));
  it('plain steel enchantment 3 sword damage 500 pays 400 G and leaves 1600 G cap', () => verify(23));
  it('rune damage 200 pays 100 G and leaves 400 G cap', () => verify(24));
  it('dragon sword enchantment 5 damage 800 pays 700 G', () => verify(25));
  it('steel sword enchantment 9 damage 1000 pays 400 G', () => verify(26));
  it('dragon sword enchantment 8 damage 1000 pays 400 G: enchantment wins', () => verify(27));
  it('dragon sword enchantment 9 damage 1000 pays 400 G: enchantment wins', () => verify(28));
  it('sword and amulet damaged 500 and 300 pay 600 G with a deductible on each damage', () => verify(29));
  it('two insured swords give 2000 G sum and 4000 G cap; two sword damages each have a deductible', () => verify(30));
  it('sword plus amulet insurance sum 1600 G gives 3200 G remaining cap', () => verify(31));
  it('cursed sword premium 165 G leaves unmodified 2000 G claim cap', () => verify(32));
  it('sword plus 3 runes has 1750 G insurance sum despite component block, cap 3500 G', () => verify(33));
  it('first sword claim for 1500 pays 1400 G and leaves 600 G cap', () => verify(34));
  it('second sword claim for 1500 pays only remaining 600 G and leaves 0 G', () => verify(35));
  it('fractional payout 350.5 G rounds down to 350 G only at end', () => verify(36));
  it('claim for uninsured amulet exits non-zero with stderr', () => verify(37));
  it('claim for unknown item type exits non-zero with stderr', () => verify(38));
  it('two sword damages against one insured sword reject entire claim non-zero with stderr', () => verify(39));
  it('negative damage -200 exits non-zero with stderr', () => verify(40));
  it('schema example quote amulet then claim 200 yields integer premium 59 G at 5 years and payout 100 G, remaining cap 1100 G', () => verify(41));
});
