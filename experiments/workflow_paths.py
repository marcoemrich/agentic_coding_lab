"""Resolve workflow names and paths.

Reads the ALIASES.json / PATHS.json generated by workflow-lineage.py. Purpose
of the split: no YAML here, so the consumers (aggregate-by-query,
batch-plan-from-rq) do not grow their dependencies.

`canonical()` is the bridge to the legacy runs. A run's metrics.json carries
forever the workflow name it ran under — these files are never rewritten,
they are recorded experiment material. Instead, both sides are canonicalised
in every comparison.
"""
import json
from pathlib import Path

WORKFLOWS_DIR = Path(__file__).resolve().parent / "workflows"
_ALIASES_FILE = WORKFLOWS_DIR / "ALIASES.json"
_PATHS_FILE = WORKFLOWS_DIR / "PATHS.json"

_aliases: dict[str, str] | None = None
_paths: dict[str, str] | None = None


def _load() -> None:
    global _aliases, _paths
    if _aliases is None:
        _aliases = json.loads(_ALIASES_FILE.read_text()) if _ALIASES_FILE.is_file() else {}
        _paths = json.loads(_PATHS_FILE.read_text()) if _PATHS_FILE.is_file() else {}


def canonical(name: str) -> str:
    """Old name -> current name. Unknown names pass through unchanged.

    Pass through instead of raising: a typo in an RQ should still surface as
    'no run matched', not as a crash of the aggregation.
    """
    _load()
    return _aliases.get(name, name)


def workflow_dir(name: str) -> Path:
    """Directory of a workflow, old names included."""
    _load()
    canon = canonical(name)
    rel = _paths.get(canon)
    return WORKFLOWS_DIR / rel if rel else WORKFLOWS_DIR / canon


def known_names() -> set[str]:
    _load()
    return set(_paths)


def is_archived(name: str) -> bool:
    """Does the workflow live under _archive/ — i.e. status: discarded?

    The folder is the trigger, not the name: aggregate-by-query aborts on an
    archived selector so discarded variants do not slip silently into a
    fresh aggregation.
    """
    _load()
    return _paths.get(canonical(name), "").startswith("_archive/")
